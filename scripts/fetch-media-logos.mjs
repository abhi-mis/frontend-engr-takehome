// Downloads the press mastheads and writes lib/press.generated.ts.
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const CDN = "https://d1zk2x7mtoyb2b.cloudfront.net/websiteAssets/featured-in-logo";

const SOURCES = [
  { key: "the-print", file: "the-print-logo.png", name: "The Print",
    href: "https://theprint.in/ani-press-releases/propsoch-redefines-homebuying-in-india-with-their-buyer-centric-advisory-model/2552423/" },
  { key: "ani", file: "ani-logo.png", name: "ANI",
    href: "https://www.aninews.in/news/business/propsoch-redefines-homebuying-in-india-with-their-buyer-centric-advisory-model20250318121741/" },
  { key: "business-standard", file: "business-standard-logo.png", name: "Business Standard",
    href: "https://www.business-standard.com/content/press-releases-ani/propsoch-redefines-homebuying-in-india-with-their-buyer-centric-advisory-model-125031800520_1.html" },
  { key: "mint", file: "mint-logo.png", name: "Mint",
    href: "https://www.business-standard.com/content/press-releases-ani/propsoch-redefines-homebuying-in-india-with-their-buyer-centric-advisory-model-125031800520_1.html" },
  { key: "realty-next", file: "realty-next-logo.png", name: "Realty NXT",
    href: "https://realtynxt.com/proptech-buzz/2025-02-18/propsoch-raises-500k-to-transform-home-buying-with-data-science-unbiased-insights-realtynxt-exclusive" },
];

const TARGET_H = 60;

const OUT_DIR = path.join(process.cwd(), "public", "press");
const MANIFEST = path.join(process.cwd(), "lib", "press.generated.ts");

async function get(url) {
  const res = await fetch(url, { headers: { "user-agent": "Mozilla/5.0" } });
  if (!res.ok) throw new Error(`HTTP ${res.status} for ${url}`);
  return Buffer.from(await res.arrayBuffer());
}

async function alphaProfile(buf) {
  const { data, info } = await sharp(buf).ensureAlpha().raw()
    .toBuffer({ resolveWithObject: true });
  let clear = 0;
  let semi = 0;
  for (let i = 3; i < data.length; i += 4) {
    const a = data[i];
    if (a === 0) clear++;
    else if (a < 250) semi++;
  }
  const px = info.width * info.height;
  return { clear: (100 * clear) / px, semi: (100 * semi) / px };
}

async function main() {
  await mkdir(OUT_DIR, { recursive: true });

  let total = 0;
  const entries = [];

  for (const source of SOURCES) {
    const src = await get(`${CDN}/${source.file}`);
    const meta = await sharp(src).metadata();
    const profile = await alphaProfile(src);

    const out = await sharp(src)
      .resize({ height: TARGET_H, fit: "inside", kernel: "lanczos3" })
      .webp({ quality: 90, alphaQuality: 100, effort: 6 })
      .toBuffer({ resolveWithObject: true });

    const file = `${source.key}.webp`;
    await writeFile(path.join(OUT_DIR, file), out.data);
    total += out.data.length;

    entries.push({ ...source, out: file, width: out.info.width, height: out.info.height });

    console.log(
      `  ${source.key.padEnd(18)} ${String(meta.width).padStart(4)}x${meta.height}` +
        ` -> ${out.info.width}x${out.info.height}` +
        ` ${(out.data.length / 1024).toFixed(1).padStart(5)}KB` +
        `  alpha: ${profile.clear.toFixed(0)}% clear, ${profile.semi.toFixed(1)}% semi`
    );
  }

  const ts = `// Generated by scripts/fetch-media-logos.mjs. Do not edit by hand.

export interface PressLogo {
  readonly src: string;
  readonly name: string;
  readonly href: string;
  readonly width: number;
  readonly height: number;
}

export const PRESS_LOGOS: readonly PressLogo[] = [
${entries
  .map(
    (e) => `  {
    src: "/press/${e.out}",
    name: ${JSON.stringify(e.name)},
    href: ${JSON.stringify(e.href)},
    width: ${e.width},
    height: ${e.height},
  },`
  )
  .join("\n")}
];
`;

  await writeFile(MANIFEST, ts, "utf8");
  console.log(`\n  ${(total / 1024).toFixed(1)} KB written, manifest at lib/press.generated.ts\n`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
